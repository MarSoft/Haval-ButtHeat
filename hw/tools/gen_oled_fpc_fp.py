#!/usr/bin/env python3
"""Generate solder pads for the 0.91" OLED glass flex (GME12832, 14 pins, 0.62 mm pitch).

Pads run along Y (pin 1 at +Y: bottom on screen = low case y), each pad long along X so the
flex contacts can be hand-soldered. Front side, under the glass end (option 3), exactly like on
the original driver board: the flex loops out past the glass end and back under it.

Usage: gen_oled_fpc_fp.py OUT.kicad_mod
"""
import sys
import uuid

N, PITCH = 14, 0.62
PAD_W, PAD_L = 0.35, 2.5
FLEX_W = 9.2                 # flex width at the solder area
NAMES = ["C2P", "C2N", "C1P", "C1N", "VBAT", "VBREF", "VSS", "VDD",
         "RES#", "SCL", "SDA", "IREF", "VCOMH", "VCC"]


def u():
    return f'(uuid "{uuid.uuid4()}")'


def rect(x1, y1, x2, y2, layer, w):
    return (f'\t(fp_rect (start {x1:.4f} {y1:.4f}) (end {x2:.4f} {y2:.4f}) '
            f'(stroke (width {w}) (type solid)) (fill no) (layer "{layer}") {u()})')


def text(kind, val, x, y, layer):
    return (f'\t(property "{kind}" "{val}" (at {x:.4f} {y:.4f} 0) (layer "{layer}") {u()}\n'
            f'\t\t(effects (font (size 0.8 0.8) (thickness 0.12))))')


span = (N - 1) * PITCH
out = ['(footprint "OLED_FPC_14P_P0.62mm"',
       '\t(version 20260206)\n\t(generator "gen_oled_fpc_fp.py")\n\t(layer "F.Cu")',
       '\t(descr "Hand-solder pads for the 0.91in OLED glass flex, 14 pins @0.62 mm '
       '(GME12832). Generated by hw/tools/gen_oled_fpc_fp.py.")',
       '\t(tags "OLED FPC flex SSD1306 0.91")',
       text("Reference", "REF**", 0, -FLEX_W / 2 - 1.0, "F.SilkS"),
       text("Value", "OLED_FPC_14P_P0.62mm", 0, FLEX_W / 2 + 1.0, "F.Fab"),
       '\t(attr smd)',
       rect(-PAD_L / 2, -FLEX_W / 2, PAD_L / 2, FLEX_W / 2, "F.Fab", 0.1),
       rect(-PAD_L / 2 - 0.3, -FLEX_W / 2 - 0.3, PAD_L / 2 + 0.3, FLEX_W / 2 + 0.3, "F.CrtYd", 0.05),
       f'\t(fp_circle (center {-PAD_L / 2 - 0.6:.4f} {span / 2:.4f}) (end {-PAD_L / 2 - 0.45:.4f} '
       f'{span / 2:.4f}) (stroke (width 0.3) (type solid)) (fill yes) (layer "F.SilkS") {u()})']
for i in range(N):
    y = span / 2 - i * PITCH
    out.append(f'\t(pad "{i + 1}" smd rect (at 0 {y:.4f}) (size {PAD_L} {PAD_W}) '
               f'(layers "F.Cu" "F.Mask") {u()})')
out.append('\t(fp_text user "' + " ".join(f"{i + 1}:{n}" for i, n in enumerate(NAMES[:7])) +
           f'" (at 0 {-FLEX_W / 2 - 2.0:.4f} 0) (layer "Cmts.User") {u()}\n'
           '\t\t(effects (font (size 0.5 0.5) (thickness 0.08))))')
out += ['\t(embedded_fonts no)', ')']

with open(sys.argv[1], "w") as f:
    f.write("\n".join(out) + "\n")
