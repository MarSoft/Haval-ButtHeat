#!/usr/bin/env python3
"""Generate the ESP32-C3 SuperMini castellated-module footprint.

Geometry from the FreeCAD model `esp32 c3 supermini v19` (3d/ButtHeatModel.FCStd):
board 18.0 x 22.8, castellations 2 x 8 at 2.54 pitch on the long edges, first pad
centre 1.54 from the USB end, USB-C overhangs the short end by 1.4 (8.94 wide).

Footprint frame: origin = module centre, USB end at +Y (screen down), top view.
Pads are named by function (standard silkscreen), so the symbol can use the same names.

Usage: gen_supermini_fp.py OUT.kicad_mod
"""
import sys
import uuid

W, L = 18.0, 22.8            # module width (X) and length (Y)
PITCH, FIRST = 2.54, 1.54    # pad pitch, first pad centre from USB end
PAD_IN, PAD_OUT = 1.2, 0.5   # carrier pad extent inside / outside the module edge
PAD_H = 1.3
USB_W, USB_OVER, USB_DEPTH = 8.94, 1.4, 7.3
ANT = 6.0                    # antenna keep-out depth at the far (non-USB) end

# from the USB end upwards, top view with USB pointing down
LEFT = ["5V", "GND", "3V3", "IO4", "IO3", "IO2", "IO1", "IO0"]
RIGHT = ["IO5", "IO6", "IO7", "IO8", "IO9", "IO10", "IO20", "IO21"]


def u():
    return f'(uuid "{uuid.uuid4()}")'


def line(x1, y1, x2, y2, layer, w):
    return (f'\t(fp_line (start {x1:.4f} {y1:.4f}) (end {x2:.4f} {y2:.4f}) '
            f'(stroke (width {w}) (type solid)) (layer "{layer}") {u()})')


def rect(x1, y1, x2, y2, layer, w):
    return (f'\t(fp_rect (start {x1:.4f} {y1:.4f}) (end {x2:.4f} {y2:.4f}) '
            f'(stroke (width {w}) (type solid)) (fill no) (layer "{layer}") {u()})')


def text(kind, val, x, y, layer, hide=False):
    h = " (hide yes)" if hide else ""
    return (f'\t(property "{kind}" "{val}" (at {x:.4f} {y:.4f} 0) (layer "{layer}"){h} {u()}\n'
            f'\t\t(effects (font (size 1 1) (thickness 0.15))))')


out = []
out.append('(footprint "ESP32-C3-SuperMini"')
out.append('\t(version 20260206)\n\t(generator "gen_supermini_fp.py")\n\t(layer "F.Cu")')
out.append('\t(descr "ESP32-C3 SuperMini castellated module, 2x8 @2.54, 18x22.8, USB-C at +Y end. '
           'Generated by hw/tools/gen_supermini_fp.py from the FreeCAD model.")')
out.append('\t(tags "ESP32-C3 SuperMini castellated module")')
yb = L / 2  # USB end
out.append(text("Reference", "REF**", 0, -yb - 1.5, "F.SilkS"))
out.append(text("Value", "ESP32-C3-SuperMini", 0, 0, "F.Fab"))
out.append('\t(attr smd)')

# fab: module outline, USB overhang, antenna area
out.append(rect(-W / 2, -yb, W / 2, yb, "F.Fab", 0.1))
out.append(rect(-USB_W / 2, yb - USB_DEPTH + USB_OVER, USB_W / 2, yb + USB_OVER, "F.Fab", 0.1))
out.append(line(-W / 2, -yb + ANT, W / 2, -yb + ANT, "F.Fab", 0.1))
out.append(f'\t(fp_text user "antenna" (at 0 {-yb + ANT / 2:.4f} 0) (layer "F.Fab") {u()}\n'
           f'\t\t(effects (font (size 0.8 0.8) (thickness 0.12))))')
out.append(f'\t(fp_text user "${{REFERENCE}}" (at 0 2 0) (layer "F.Fab") {u()}\n'
           f'\t\t(effects (font (size 1 1) (thickness 0.15))))')
# silk: short ends only (long edges are pads); pin-1 (5V) marker
out.append(line(-W / 2 - 0.2, -yb - 0.2, W / 2 + 0.2, -yb - 0.2, "F.SilkS", 0.12))
out.append(line(-W / 2 - 0.2, yb + 0.2, -USB_W / 2 - 0.2, yb + 0.2, "F.SilkS", 0.12))
out.append(line(USB_W / 2 + 0.2, yb + 0.2, W / 2 + 0.2, yb + 0.2, "F.SilkS", 0.12))
p1y = yb - FIRST
out.append(f'\t(fp_circle (center {-W / 2 - PAD_OUT - 0.6:.4f} {p1y:.4f}) '
           f'(end {-W / 2 - PAD_OUT - 0.4:.4f} {p1y:.4f}) (stroke (width 0.2) (type solid)) '
           f'(fill yes) (layer "F.SilkS") {u()})')
# courtyard
cx = W / 2 + PAD_OUT + 0.25
out.append(rect(-cx, -yb - 0.25, cx, yb + USB_OVER + 0.25, "F.CrtYd", 0.05))

# pads
pw = PAD_IN + PAD_OUT
for side, names in ((-1, LEFT), (1, RIGHT)):
    xc = side * (W / 2 + PAD_OUT - pw / 2)
    for i, n in enumerate(names):
        y = yb - FIRST - i * PITCH
        out.append(f'\t(pad "{n}" smd roundrect (at {xc:.4f} {y:.4f}) (size {pw:.3f} {PAD_H:.3f}) '
                   f'(layers "F.Cu" "F.Mask" "F.Paste") (roundrect_rratio 0.15) {u()})')

# antenna keep-out: no copper pour under the antenna end (tracks, vias and pads are allowed)
ka = [(-W / 2, -yb), (W / 2, -yb), (W / 2, -yb + ANT), (-W / 2, -yb + ANT)]
pts = " ".join(f"(xy {x:.4f} {y:.4f})" for x, y in ka)
out.append(f'\t(zone (net 0) (net_name "") (layers "F.Cu" "B.Cu") {u()} (name "SuperMini antenna")\n'
           f'\t\t(hatch edge 0.5) (connect_pads (clearance 0))\n'
           f'\t\t(min_thickness 0.25) (filled_areas_thickness no)\n'
           f'\t\t(keepout (tracks allowed) (vias allowed) (pads allowed) '
           f'(copperpour not_allowed) (footprints allowed))\n'
           f'\t\t(fill (thermal_gap 0.5) (thermal_bridge_width 0.5))\n'
           f'\t\t(polygon (pts {pts})))')
out.append('\t(embedded_fonts no)')
out.append(')')

with open(sys.argv[1], "w") as f:
    f.write("\n".join(out) + "\n")
