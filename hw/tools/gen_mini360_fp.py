#!/usr/bin/env python3
"""Generate the Mini360 (MP2307) buck-module footprint.

Datasheet: board 17.272 x 11.176 x 3.8 (1.0 PCB), 4 corner holes on 15.24 x 9.144 centres.
Laid horizontally (long side along X), top view: top-left IN-, bottom-left IN+,
top-right OUT-, bottom-right OUT+. 12 uF caps on both sides are on the module.

Usage: gen_mini360_fp.py OUT.kicad_mod
"""
import sys
import uuid

L, W = 17.272, 11.176
DX, DY = 15.24 / 2, 9.144 / 2
DRILL, PAD = 1.0, 1.8
PADS = {"IN-": (-DX, -DY), "IN+": (-DX, DY), "OUT-": (DX, -DY), "OUT+": (DX, DY)}


def u():
    return f'(uuid "{uuid.uuid4()}")'


def rect(x1, y1, x2, y2, layer, w):
    return (f'\t(fp_rect (start {x1:.4f} {y1:.4f}) (end {x2:.4f} {y2:.4f}) '
            f'(stroke (width {w}) (type solid)) (fill no) (layer "{layer}") {u()})')


def prop(kind, val, x, y, layer):
    return (f'\t(property "{kind}" "{val}" (at {x:.4f} {y:.4f} 0) (layer "{layer}") {u()}\n'
            f'\t\t(effects (font (size 1 1) (thickness 0.15))))')


out = ['(footprint "Mini360"',
       '\t(version 20260206)\n\t(generator "gen_mini360_fp.py")\n\t(layer "F.Cu")',
       '\t(descr "Mini360 (MP2307) buck module 17.272x11.176x3.8, 4 corner THT pads on 15.24x9.144. '
       'Generated by hw/tools/gen_mini360_fp.py.")',
       '\t(tags "buck DC-DC module Mini360 MP2307")',
       prop("Reference", "REF**", 0, -W / 2 - 1.2, "F.SilkS"),
       prop("Value", "Mini360", 0, 0, "F.Fab"),
       '\t(attr through_hole)',
       rect(-L / 2, -W / 2, L / 2, W / 2, "F.Fab", 0.1),
       rect(-L / 2 - 0.12, -W / 2 - 0.12, L / 2 + 0.12, W / 2 + 0.12, "F.SilkS", 0.12),
       rect(-L / 2 - 0.25, -W / 2 - 0.25, L / 2 + 0.25, W / 2 + 0.25, "F.CrtYd", 0.05),
       f'\t(fp_text user "IN" (at {-DX + 2.2:.4f} 0 0) (layer "F.SilkS") {u()}\n'
       f'\t\t(effects (font (size 0.8 0.8) (thickness 0.12))))',
       f'\t(fp_text user "OUT" (at {DX - 2.5:.4f} 0 0) (layer "F.SilkS") {u()}\n'
       f'\t\t(effects (font (size 0.8 0.8) (thickness 0.12))))']
for name, (x, y) in PADS.items():
    shape = "rect" if name == "IN+" else "circle"
    out.append(f'\t(pad "{name}" thru_hole {shape} (at {x:.4f} {y:.4f}) (size {PAD} {PAD}) '
               f'(drill {DRILL}) (layers "*.Cu" "*.Mask") {u()})')
out += ['\t(embedded_fonts no)', ')']

with open(sys.argv[1], "w") as f:
    f.write("\n".join(out) + "\n")
