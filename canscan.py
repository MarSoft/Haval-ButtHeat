"""
Scan CAN log generated by SavvyCAN for given idents
"""
from collections import defaultdict
import csv
import sys

canfile = sys.argv[1]
idents = [int(a, 16) for a in sys.argv[2]]

with open(canfile, 'r') as f:
    reader = csv.DictReader(f)
    last_ts = 0
    last_vals = defaultdict(lambda: [0, 0, 0, 0, 0, 0, 0, 0])
    for r in reader:
        cur_id = int(r['ID'], 16)
        if cur_id not in idents:
            continue
        last_val = last_vals[cur_id]
        cur_ts = int(r['Time Stamp'])
        cur_val = [int(r[f'D{n}'], 16) for n in range(1, 9)]
        if cur_val != last_val:
            f = ' '.join(f'{d:02x}' for d in cur_val)
            print(f'Change at TS {last_ts}->{cur_ts}: {f}')
        last_ts = cur_ts
        last_vals[cur_id] = cur_val
